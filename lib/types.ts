export type SourceType = "sysmon" | "winsec" | "proxy" | "defender";

export interface LogEvent {
  id: string; // "EVT-0017"
  timestamp: string; // ISO 8601 UTC
  source: SourceType;
  host: string;
  event_id: number | string;
  raw: Record<string, unknown>; // the full original JSON line
  summary: string; // one-line, generated by summarize()
}

export type EntryKind = "fact" | "hypothesis" | "unknown";
export type FactStatus = "confirmed" | "unverified"; // only for kind === "fact"
export type Relation = "supports" | "contradicts" | "related";

export interface MatchedField {
  field: string;
  value: string;
}

export interface EvidenceLink {
  eventId: string;
  relation: Relation;
  matchedFields: MatchedField[]; // must exist verbatim in event.raw
}

export interface LedgerEntry {
  id: string; // "OBS-001", "HYP-001", "UNK-001"
  kind: EntryKind;
  status?: FactStatus;
  text: string;
  eventTime?: string;
  noteId: string;
  evidence: EvidenceLink[];
  createdAt: string;
  resolvedBy?: string;
  analystEdited: boolean;
}

export interface Note {
  id: string; // "NOTE-004"
  text: string;
  createdAt: string;
  pinnedEventIds: string[];
  parser: "model" | "offline";
}

export interface Contradiction {
  id: string; // "CON-001"
  kind: "claim_vs_evidence" | "claim_vs_claim";
  entryId: string;
  againstEntryId?: string;
  againstEventId?: string;
  explanation: string;
  state: "open" | "resolved" | "dismissed";
  resolutionNote?: string;
}

export type Severity = "low" | "medium" | "high" | "critical";
export type CaseStatus = "open" | "contained" | "closed";

export interface Activity {
  at: string;
  actor: "analyst" | "system";
  text: string;
}

export interface Case {
  id: string;
  title: string;
  severity: Severity;
  status: CaseStatus;
  analyst: string;
  timezone: string;
  caseDate: string; // YYYY-MM-DD
  events: LogEvent[];
  notes: Note[];
  entries: LedgerEntry[];
  contradictions: Contradiction[];
  activity: Activity[];
}

/** Parser output before IDs are assigned (shape of the zod ParseResult). */
export interface DraftEntry {
  tempId: string;
  kind: EntryKind;
  text: string;
  eventTime: string | null;
  evidence: EvidenceLink[];
  answersUnknownIds: string[];
}

export interface DraftContradiction {
  kind: "claim_vs_evidence" | "claim_vs_claim";
  entryTempId: string;
  againstEventId: string | null;
  againstEntryId: string | null;
  explanation: string;
}

export interface ParseResultT {
  entries: DraftEntry[];
  contradictions: DraftContradiction[];
}

/** What the client sends to /api/parse. */
export interface CompactEvent {
  id: string;
  timestamp: string;
  source: SourceType;
  event_id: number | string;
  raw: Record<string, unknown>;
}

export interface LedgerSummary {
  id: string;
  kind: EntryKind;
  status?: FactStatus;
  text: string;
  evidence: string[];
  resolved?: boolean; // unknowns already answered
}

export interface ParseRequest {
  mode: "parse" | "recheck";
  note: string;
  pinnedEventIds: string[];
  timezone: string;
  caseDate: string;
  ledger: LedgerSummary[];
  candidates: CompactEvent[];
  /** recheck only: the entries being rechecked, keyed by tempId = entry ID */
  recheck?: { id: string; kind: EntryKind; text: string }[];
}

export interface ParseResponse {
  parser: "model" | "offline";
  fallbackReason?: string;
  result: ParseResultT;
  rejected: string[]; // human-readable notes about dropped links
}
